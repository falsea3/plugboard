package postgres

import (
	"context"
	"database/sql"
	"fmt"
	"io"
	"strings"

	"github.com/jackc/pgx/v5/stdlib"
)

func (d Dialect) relName(r pgRel) string {
	return d.QuoteIdent(r.schema) + "." + d.QuoteIdent(r.name)
}

func (d Dialect) dumpTableDDL(r pgRel, parent string, cols []pgCol, checks []pgConstraint, identity func(pgCol) string) string {
	name := d.relName(r)
	head := "CREATE TABLE "
	if r.unlogged {
		head = "CREATE UNLOGGED TABLE "
	}
	var lines []string
	for _, c := range checks {
		lines = append(lines, "CONSTRAINT "+d.QuoteIdent(c.name)+" "+c.def)
	}
	var out string
	if r.partBound.Valid && parent != "" {
		out = head + name + " PARTITION OF " + parent
		if len(lines) > 0 {
			out += " (\n    " + strings.Join(lines, ",\n    ") + "\n)"
		}
		out += "\n" + r.partBound.String
	} else {
		var colLines []string
		for _, c := range cols {
			if parent != "" && !c.local {
				continue
			}
			colLines = append(colLines, d.columnLine(c, identity(c)))
		}
		out = head + name + " (\n    " + strings.Join(append(colLines, lines...), ",\n    ") + "\n)"
		if parent != "" {
			out += "\nINHERITS (" + parent + ")"
		}
	}
	if r.partKey.Valid {
		out += "\nPARTITION BY " + r.partKey.String
	}
	if r.options.Valid && r.options.String != "" {
		out += "\nWITH (" + r.options.String + ")"
	}
	return out + ";"
}

func (d Dialect) columnLine(c pgCol, identity string) string {
	line := d.QuoteIdent(c.name) + " " + c.typ
	if c.collation.Valid {
		line += " COLLATE " + c.collation.String
	}
	switch {
	case c.generated == "s" && c.def.Valid:
		line += " GENERATED ALWAYS AS (" + c.def.String + ") STORED"
	case c.identity == "a":
		line += " GENERATED ALWAYS AS IDENTITY" + identity
	case c.identity == "d":
		line += " GENERATED BY DEFAULT AS IDENTITY" + identity
	case c.def.Valid:
		line += " DEFAULT " + c.def.String
	}
	if c.notNull && c.identity == "" {
		line += " NOT NULL"
	}
	return line
}

func (d Dialect) dataColumns(cols []pgCol) []string {
	var out []string
	for _, c := range cols {
		if c.generated == "" {
			out = append(out, d.QuoteIdent(c.name))
		}
	}
	return out
}

func (d Dialect) copyOut(ctx context.Context, conn *sql.Conn, w io.Writer, name string, cols []string) (int64, error) {
	list := strings.Join(cols, ", ")
	var rows int64
	err := conn.Raw(func(dc any) error {
		tag, err := dc.(*stdlib.Conn).Conn().PgConn().CopyTo(ctx, w, fmt.Sprintf("COPY %s (%s) TO STDOUT", name, list))
		rows = tag.RowsAffected()
		return err
	})
	if err != nil {
		return rows, err
	}
	_, err = io.WriteString(w, "\\.\n")
	return rows, err
}

func (d Dialect) insertsOut(ctx context.Context, conn *sql.Conn, w io.Writer, name string, cols []string, overriding bool) (int64, error) {
	quoted := make([]string, len(cols))
	for i, c := range cols {
		quoted[i] = "quote_nullable(" + c + ")"
	}
	rows, err := conn.QueryContext(ctx, fmt.Sprintf("SELECT concat_ws(', ', %s) FROM ONLY %s", strings.Join(quoted, ", "), name))
	if err != nil {
		return 0, err
	}
	defer rows.Close()
	head := fmt.Sprintf("INSERT INTO %s (%s)", name, strings.Join(cols, ", "))
	if overriding {
		head += " OVERRIDING SYSTEM VALUE"
	}
	head += " VALUES\n"
	var n int64
	batch := 0
	for rows.Next() {
		var values string
		if err := rows.Scan(&values); err != nil {
			return n, err
		}
		sep := ",\n"
		if batch == 0 {
			sep = head
		}
		if _, err := io.WriteString(w, sep+"("+values+")"); err != nil {
			return n, err
		}
		n++
		if batch++; batch == 200 {
			batch = 0
			if _, err := io.WriteString(w, ";\n"); err != nil {
				return n, err
			}
		}
	}
	if batch > 0 {
		if _, err := io.WriteString(w, ";\n"); err != nil {
			return n, err
		}
	}
	if n > 0 {
		_, err = io.WriteString(w, "\n")
	}
	return n, rows.Err()
}

func (Dialect) CopyIn(ctx context.Context, conn *sql.Conn, stmt string, data io.Reader) (int64, error) {
	var rows int64
	err := conn.Raw(func(dc any) error {
		tag, err := dc.(*stdlib.Conn).Conn().PgConn().CopyFrom(ctx, data, stmt)
		rows = tag.RowsAffected()
		return err
	})
	return rows, err
}
